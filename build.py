"""Bundle the app into one self-contained page.

Writes index.html at the repository root, which is what GitHub Pages serves.
Run:  python3 build.py
"""
import base64
import pathlib

root = pathlib.Path(__file__).parent
src = root / 'src'
logo = base64.b64encode((root / 'assets' / 'logo.jpg').read_bytes()).decode()
js = '\n'.join((src / f).read_text() for f in ['core.js', 'seed.js', 'store.js', 'pdf.js', 'config.js', 'remote.js', 'app.js'])
html = (src / 'template.html').read_text()
html = html.replace('/*__CSS__*/', (src / 'styles.css').read_text())
html = html.replace('/*__LOGO__*/', 'data:image/jpeg;base64,' + logo)
presenter = base64.b64encode((root / 'assets' / 'presenter.jpg').read_bytes()).decode()
html = html.replace('/*__PRESENTER__*/', 'data:image/jpeg;base64,' + presenter)
html = html.replace('/*__JS__*/', js.replace('</script', '<\\/script'))
import sys
if '--preview' in sys.argv:
    # Preview build: practice data only (never touches the live database).
    target = pathlib.Path(sys.argv[sys.argv.index('--preview') + 1])
    cfg = (src / 'config.js').read_text()
    html = html.replace(cfg, 'window.WAPCPD_CONFIG = null; window.WAPCPD_PREVIEW = true;\n')
    assert 'WAPCPD_PREVIEW = true' in html
    target.write_text(html)
    print(target, len(html) // 1024, 'KB (preview)')
    sys.exit(0)
out = root / 'index.html'
out.write_text(html)
print(out, len(html) // 1024, 'KB')

# Server program for Supabase: the Edge Function uses the same rules engine.
fn = root / 'supabase' / 'functions'
(fn / 'cpd').mkdir(parents=True, exist_ok=True)
(fn / '_shared').mkdir(parents=True, exist_ok=True)
(fn / 'cpd' / 'index.ts').write_text((root / 'server' / 'index.ts').read_text())
for name, source in [('core.js', src / 'core.js'), ('handler.js', root / 'server' / 'handler.js'), ('staff.js', root / 'server' / 'staff.js')]:
    (fn / '_shared' / name).write_text('// Generated by build.py from ' + str(source.relative_to(root)) + ' — do not edit here.\n' + source.read_text())
print(fn, 'updated')
